def arm_source():
    blurb = (" * M0 MAC %s XID %s / M33 MAC %s XID %s." % (
        ":".join(f"{b:02X}" for b in ARCHES["m0"]["mac"]),
        ARCHES["m0"]["xid"].hex(), ":".join(f"{b:02X}" for b in ARCHES["m33"]["mac"]),
        ARCHES["m33"]["xid"].hex()))
    # One source, two builds: M0 vs M33 differ only in addresses (ifdef)
    # — but MAC/XID differ per arch, so emit BOTH blob sets, select
    # with #ifdef RP2350.
    out = []
    for tag, m, x in (("M0", ARCHES["m0"]["mac"], ARCHES["m0"]["xid"]),
                      ("M33", ARCHES["m33"]["mac"], ARCHES["m33"]["xid"])):
        d = build_discover(m, x)
        r = build_request(m, x, OFFER_IP, SERVER_IP)
        out.append((tag, d, r))
    lines = []
    for tag, d, r in out:
        sel = "#ifdef RP2350" if tag == "M33" else "#ifndef RP2350"
        lines.append(sel)
        lines.append(f"disc_blob:  /* {tag} DISCOVER {len(d)}B */")
        lines.append(blob_lines(d))
        lines.append(f"req_blob:   /* {tag} REQUEST {len(r)}B */")
        lines.append(blob_lines(r))
        lines.append("#endif")
    blobs = "\n".join(lines)
    src = ARM_TEMPLATE
    # lengths identical across arches (same layout)? Verify, then bake in.
    assert len(out[0][1]) == len(out[1][1]) and len(out[0][2]) == len(out[1][2]), \
        (len(out[0][1]), len(out[1][1]), len(out[0][2]), len(out[1][2]))
    # Frame lens are 342 (0x156): BOTH bytes must be backed in, because
    # movs can only carry 0..255 — (#(86)/#(1) here would truncate to 86B
    # and the gateway would see a runt DISCOVER with no magic/cookie).
    dd, dr = len(out[0][1]), len(out[0][2])
    assert dd == 342 and dr == 342, (dd, dr)
    src = src.replace("movs r2, #(__DISC_LEN_LO__)", f"movs r2, #({dd & 0xFF})")
    src = src.replace("movs r3, #(__DISC_LEN_HI__)", f"movs r3, #({(dd >> 8) & 0xFF})")
    src = src.replace("movs r1, #(__DISC_LEN_LO__)", f"movs r1, #({dd & 0xFF})")
    src = src.replace("movs r2, #(__DISC_LEN_HI__)", f"movs r2, #({(dd >> 8) & 0xFF})")
    src = src.replace("movs r2, #(__REQ_LEN_LO__)", f"movs r2, #({dr & 0xFF})")
    src = src.replace("movs r3, #(__REQ_LEN_HI__)", f"movs r3, #({(dr >> 8) & 0xFF})")
    src = src.replace("movs r1, #(__REQ_LEN_LO__)", f"movs r1, #({dr & 0xFF})")
    src = src.replace("movs r2, #(__REQ_LEN_HI__)", f"movs r2, #({(dr >> 8) & 0xFF})")
    # XID differs per arch: ifdef at the two compare sites
    src = src.replace("cmp r1, #__XID0__",
                      "#ifdef RP2350\ncmp r1, #0x%02X\n#else\ncmp r1, #0x%02X\n#endif"
                      % (ARCHES["m33"]["xid"][0], ARCHES["m0"]["xid"][0]))
    src = src.replace("cmp r1, #__XID1__",
                      "#ifdef RP2350\ncmp r1, #0x%02X\n#else\ncmp r1, #0x%02X\n#endif"
                      % (ARCHES["m33"]["xid"][1], ARCHES["m0"]["xid"][1]))
    mac_m0 = ",".join(f"0x{b:02X}" for b in ARCHES["m0"]["mac"])
    mac_m33 = ",".join(f"0x{b:02X}" for b in ARCHES["m33"]["mac"])
    # NOTE: NO `mac_addr = ...` alias — build_eth.py only handles ABS32
    # against section symbols; an .equ-to-symbol alias emits R_ARM_NONE
    # (silently unpatched -> pool slot 0 -> mac read from string bytes).
    # Both code sites use the RP2350 ifdef directly instead.
    src = src.replace("mac_addr: .byte __MAC__",
                      "mac_addr_m33: .byte " + mac_m33 +
                      "\nmac_addr_m0: .byte " + mac_m0)
    src = src.replace("__DISC_BLOB__\n__REQ_BLOB__", blobs)
    src = src.replace("__BLURB__", "\n" + blurb)
    return src


def main():
    arm = arm_source()
    open(os.path.join(D, "eth_dhcp.S"), "w").write(arm)
    print("wrote", os.path.join(D, "eth_dhcp.S"))
    # RV32 source is appended to gen_rv32.py DEMOS instead (keeps rvlink
    # flow identical); see gen function below.
