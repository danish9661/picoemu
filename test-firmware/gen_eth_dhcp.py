def blob_lines(blob, per_line=12):
    out = []
    for i in range(0, len(blob), per_line):
        chunk = blob[i:i + per_line]
        out.append("    .byte " + ", ".join(f"0x{b:02X}" for b in chunk))
    return "\n".join(out)


