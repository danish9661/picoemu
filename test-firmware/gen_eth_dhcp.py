#!/usr/bin/env python3
"""Generate eth_dhcp guest firmware: full ioLibrary-style DHCP client over
W5500 MACRAW socket 0 (single-gateway path), for M0+ / M33 / RV32.

Generates:
  test-firmware/eth_dhcp.S      ARM (RP2040 ifdefs; M0+ v6m-safe / M33)
  test-firmware/eth_dhcp_rv32.S RV32 (gen_rv32.py Demo style, rvlink.py)

Flow (identical on all chips, only addresses differ):
  1. UART init, print "ETH DHCP-START"
  2. SPI0 init (CR0=7 8-bit Motorola, CPSR=2, CR1=SSE)
  3. GPIO17 OE (CSn output), CS high idle
  4. VERSIONR read (expect 0x04) else "ETH FAIL VERSION"
  5. Sn_MR=MACRAW, OPEN sock0, expect SR=0x42 else "ETH FAIL OPEN"
  6. Build DHCP DISCOVER (xid per arch), write TX buf, TX_WR=len, SEND
  7. Poll RX_RSR + Sn_IR RECV (bounded) else "ETH FAIL OFFER-TIMEOUT"
  8. Read RX buffer, parse OFFER yiaddr, print "ETH OFFER IP=<a.b.c.d>"
  9. Build DHCP REQUEST (req IP = offered), SEND, poll ACK
  10. Parse ACK yiaddr, print "ETH IP=<a.b.c.d>", "ETH DONE"
  Failures print "ETH FAIL <reason>" (sweep greps ETH DONE).

Frame layout (all multi-byte fields big-endian on the wire):
  ETH: dst(6) src=SHAR(6) type 0800 | IPv4 | UDP | BOOTP/DHCP
  BOOTP: op=1 htype=1 hlen=6 hops=0 | xid(4) | secs=0 flags=0x8000 |
         ciaddr=0 yiaddr=0 siaddr=0 giaddr=0 | chaddr=SHAR+10 zero |
         sname(64) file(128) zero | magic 63,82,53,63 | opts | end 0xFF
  DISCOVER opts: 53,1,1 | 55,1,1(subnet) 55,1,3(router) 55,1,6(dns) |
                 12 hostname "pico-eth" | end
  REQUEST opts: 53,1,3 | 50,4,req_ip | 54,4,server_ip | end
  OFFER/ACK parse: yiaddr @bootp+16, msg type opt 53, server id opt 54.

Guest embeds DISCOVER/REQUEST as .byte blobs (from eth_dhcp_common.py) —
no guest-side checksums, no 300-byte runtime frame build. Parse side
stays byte-at-a-time against RXBUF (works on all arches).

W5500 SPI framing (VDM, CS bit-banged GPIO17):
  write: ah, al, (bsb<<3)|0x04, data...
  read:  ah, al, (bsb<<3)|0x00, 0xFF -> MISO
  sock0 regs BSB=1, TX buf BSB=2, RX buf BSB=3.
  MR=0x00 CR=0x01 IR=0x02 SR=0x03 TX_WR0=0x24 RSR0=0x26 RD0=0x28.
  MACRAW=0x04 OPEN=0x01 SEND=0x20 RECV=0x40. SR_MACRAW=0x42.
  IR RECV=0x04 SEND_OK=0x10 (W1C on write).
MACRAW RX layout: [len_hi,len_lo,frame...] per queued frame.

Per-arch constants:
  M0  (RP2040): UART0 0x40034000, SPI0 0x4003C000, RAM 0x20000000/264K
  M33 (RP2350): UART0 0x40070000, SPI0 0x40080000, RAM 0x20000000/520K
  RV32(RP2350): UART0 0x40070000, SPI0 0x40080000, RAM 0x20000000/520K
SIO base is 0xD0000000 on all three.
MAC: 02:11:22:33:44:5X (M0=0x60 M33=0x61 RV32=0x62).
XID: M0=A0.. M33=B0.. RV32=C0.. + fixed tail.

ARM codegen rules (M0+ Thumb-1 hard limits — the old hand .S died here):
  - NO ldr rX, =sym inside a function that also calls bl far away:
    the literal pool lands >1KB away (out of range fixup). Instead each
    function opens with a trampoline header: local literals + b body.
    Pattern:  b 1f | .ltorg-equivalent word block | 1: ... code ...
    Concretely: emit .word literals right after function entry branch,
    load via ldr [pc,#imm<1KB] — always in range since pool is adjacent.
  - Simpler rule used here: keep every function SMALL (<~200B) and put
    .ltorg after reset_handler and mid-file; ldr=addr pools stay close.
  - NO [Rn,#imm>31] byte ops, NO adds Rd,Rn,#imm>7: stepwise adds only.
  - NO high-reg arithmetic (adds r1,r4,#imm with r4>7 needs Thumb-2).
  - NO adcs/sbcs #imm.
  - bl range on v6m is +/-4MB: fine across the whole image.
RV32 codegen: gen_rv32.py Demo style (auipc string refs), linked by rvlink.py.

Run: python3 test-firmware/gen_eth_dhcp.py (writes eth_dhcp.S + eth_dhcp_rv32.S).
"""
