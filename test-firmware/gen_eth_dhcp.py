    req = build_request(mac, xid, OFFER_IP, SERVER_IP)
    assert len(disc) < 2048 and len(req) < 2048
    assert -2048 <= len(disc) <= 2047 and -2048 <= len(req) <= 2047, \
        (len(disc), len(req))
